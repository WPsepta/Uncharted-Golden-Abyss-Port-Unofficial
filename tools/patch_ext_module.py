#!/usr/bin/env python3
"""patch_ext_module.py — muat dump modul eksternal (0x0c200000) ke guest.

Alamat entry thread game (0x0c20xxxx) berada di modul sistem Vita yang tidak
ada di dalam ELF utama. Karena alamat itu di luar guest window (0x81000000..),
modul tidak bisa dipetakan di alamat aslinya. Solusinya:

  * dump 64 KB dari 0x0c200000 disimpan sebagai array C++ (ext_module.cpp.inc)
  * array itu disalin ke guest memory di 0x81F10000 (masih dalam window,
    tepat di atas trampoline 0x81F00000)
  * FIX create-thread mengalihkan entry 0x0c20xxxx -> 0x81F10000 + offset

Pemakaian:
    python3 tools/patch_ext_module.py <app/src/main/cpp> [--dump <file.bin>]

Tanpa --dump, tool hanya mengecek apakah data sudah ada (idempotent).
"""
from __future__ import annotations

import sys
from pathlib import Path

SRC_BASE = 0x0C200000
DST_BASE = 0x81F10000
DUMP_SIZE = 0x10000  # 64 KB
INC_NAME = "ext_module.cpp.inc"
MARK = "[EXT_MOD]"
LOAD_ANCHOR = "    engine_logf(\"rc_boot OK: guest memory 256 MiB terpetakan.\");"


def load_dump(path: Path) -> bytes | None:
    if not path.exists():
        return None
    data = path.read_bytes()
    if len(data) > DUMP_SIZE:
        data = data[:DUMP_SIZE]
    if len(data) < DUMP_SIZE:
        data = data + b"\x00" * (DUMP_SIZE - len(data))
    return data


def emit_inc(data: bytes, out: Path) -> None:
    lines = [
        f"// {MARK} GENERATED by tools/patch_ext_module.py — do not edit.",
        f"// Dump guest memory 0x{SRC_BASE:08x}..0x{SRC_BASE+DUMP_SIZE:08x}",
        f"// Dipetakan ke guest 0x{DST_BASE:08x} (dalam window kMemBase).",
        "#include <cstdint>",
        "namespace rc {",
        f"extern const uint8_t ext_module_dump[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
    lines += ["};", "}  // namespace rc", ""]
    out.write_text("\n".join(lines), encoding="utf-8")


def patch_android_main(path: Path, inc_path: Path) -> bool:
    text = path.read_text(encoding="utf-8", errors="surrogateescape")
    if MARK in text:
        return False
    if LOAD_ANCHOR not in text:
        raise RuntimeError(f"anchor tidak ditemukan di {path}")
    load = (
        LOAD_ANCHOR + "\n"
        f"    // {MARK} Muat dump modul eksternal ke guest 0x{DST_BASE:08x}.\n"
        "    {\n"
        "        extern const uint8_t ext_module_dump[];\n"
        f"        const uint32_t _dst = 0x{DST_BASE:08x}u;\n"
        f"        const size_t _n = {DUMP_SIZE}u;\n"
        "        if (_dst >= rc::kMemBase && _dst + _n <= rc::kMemBase + rc::kMemSize) {\n"
        "            std::memcpy(s->cpu.mem + (_dst - rc::kMemBase), ext_module_dump, _n);\n"
        f"            engine_logf(\"{MARK}: modul 0x{SRC_BASE:08x} dimuat ke guest 0x{DST_BASE:08x} ({_n} byte).\");\n"
        "        }\n"
        "    }"
    )
    path.write_text(text.replace(LOAD_ANCHOR, load, 1),
                    encoding="utf-8", errors="surrogateescape")
    return True


def main(argv: list[str]) -> int:
    args = list(argv[1:])
    dump_path = None
    if "--dump" in args:
        i = args.index("--dump")
        if i + 1 >= len(args):
            print("error: --dump butuh path", file=sys.stderr)
            return 2
        dump_path = Path(args[i + 1])
        del args[i:i + 2]
    if len(args) != 1:
        print("pemakaian: patch_ext_module.py <app/src/main/cpp> [--dump <file.bin>]",
              file=sys.stderr)
        return 2
    root = Path(args[0])
    inc = Path(__file__).resolve().parent / INC_NAME

    data = load_dump(dump_path) if dump_path else None
    if data is None:
        if not inc.exists():
            print("error: belum ada dump. Taruh file di /storage/emulated/0/Download/ext_module.bin "
                  "lalu jalankan dengan --dump.", file=sys.stderr)
            return 1
        print(f"OK: memakai {INC_NAME} yang sudah ada ({inc.stat().st_size} byte source).")
    else:
        emit_inc(data, inc)
        print(f"OK: dump {len(data)} byte -> {inc}")

    changed = patch_android_main(root / "android_main.cpp", inc)
    print(f"OK: android_main.cpp {'dipatch' if changed else 'sudah terpatch'} ({MARK}).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
